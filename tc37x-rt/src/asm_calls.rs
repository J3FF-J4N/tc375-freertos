use core::arch::asm;

/// Enable global interrupts of Aurix microcontroller.
pub fn enable_interrupts() {
    unsafe {
        asm!("enable");
    }
}
/// Disable global interrupts of Aurix microcontroller.
pub fn disable_interrupts() {
    unsafe {
        asm!("disable");
    }
}

/// Wrapper for `MFCR`(Move From Core Register) instruction.
///
/// # Example
///
/// ```
/// const CPU_ID: u16 = 0xFE18;
/// let cpu_id = mfcr::<CPU_ID>();
/// ```
#[must_use]
pub fn mfcr<const ADDR: u16>() -> u32 {
    let mut result: u32;
    unsafe {
        asm!("mfcr {}, {}", out(reg32) result, const ADDR);
    }
    result
}

/// Wrapper for `MTCR`(Move To Core Register) instruction.
///
/// # Example
/// ```
/// const PC_ADDR: u16 = 0xFE20;
/// mtcr::<PC_ADDR>(0x1323);
/// ```
pub fn mtcr<const ADDR: u16>(value: u32) {
    unsafe {
        asm!("mtcr {}, {}", const ADDR, in(reg32) value);
        asm!("isync");
    }
}

/// Read CPU core id.
#[must_use]
pub fn read_cpu_core_id() -> u32 {
    /** \brief FE1C, `CPUx` Core Identification Register */
    const CPU_CORE_ID: u16 = 0xFE1C;

    mfcr::<CPU_CORE_ID>()
}
