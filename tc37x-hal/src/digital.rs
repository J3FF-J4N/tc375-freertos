/// Traits of [`embedded_hal::digital::v2`] module are implemented here.
///
/// Every port (e.g. port_00, port_33) has a separated module containing structures for pins.
/// These modules are bundled together with a feature. E.g. port_33 module is compiled when
/// port_33 feature is turned on in `Cargo.toml`.  
///
/// A `port_XX` feature will turn on the same feature of
/// [`tc37xpd`] library. For every supported feature, see `Cargo.toml` file
/// of current [`tc37x-hal`] package.
///
/// ### Examples
/// Using Pin05 or Port_00 ([`v2::port_00::Pin05`])
/// ``` rust
/// use embedded_hal::digital::v2::{InputPin, OutputPin, ToggleableOutputPin};
/// use tc37x_hal::digital::v2::{ self as gpio, GpioExt };
///
/// let parts = tc37xpd::P00.split();
/// let mut pin = parts.pin05;
/// pin.into_output_push_pull();
/// pin.set_high().unwrap();
/// pin.toggle().unwrap();
/// ```
pub mod v2;
