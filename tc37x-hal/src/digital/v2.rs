/// Extension trait to split a GPIO peripheral in independent pins.
///
/// Every port structure (e.g. [`tc37xpd::P00`]) implements this trait.
///
/// The split function returns a `Parts` structure which contains a `PinXX` structure for every pin of current port.
/// ### Example:
/// ``` rust
/// use tc37x_hal::digital::v2::GpioExt;
///
/// let parts = tc37xpd::P33.split();
/// ```
pub trait GpioExt {
    /// This type is defined for every port. It should contain structures represented each pins of a GPIO port.
    ///
    /// For an example, see [`p00::Parts`]!
    type Parts;

    /// Return a `Part` structure, which is used to split a GPIO port into pins.
    fn split(self) -> Self::Parts;
}

mod port_control_codes {
    pub const INPUT_PULL_DOWN: u8 = 0b00001_u8;
    pub const INPUT_PULL_UP: u8 = 0b00010_u8;
    pub const OUTPUT_PUSH_PULL: u8 = 0b10000_u8;
    pub const OUTPUT_OPEN_DRAIN: u8 = 0b11000_u8;
}

/// Module contains constants for configure GPIO line's output driver strength and slew rate.
///
/// The constants defined here are used to configure pad driver mode for GPIO ports with the
/// **PDR0** and **PDR1** registers. See section 16.4.3. of *AURIX™ TC3xx Target Specification* document.
pub mod pad_driver_codes {

    /// Pad driver mode selection for RFast pads
    pub enum RFastPadOutputCodes {
        StrongDriverSharpEdge = 0b00,
        StrongDriverMediumEdge = 0b01,
        MediumDriver = 0b10,
        RgmiiDriver = 0b11,
    }

    /// Pad driver mode selection for Fast pads
    pub enum FastPadOutputCodes {
        StrongDriverSharpEdge = 0b00,
        StrongDriverMediumEdge = 0b01,
        MediumDriver = 0b10,
        Tc39xAStepMediumDriver = 0b11,
    }

    /// Pad driver mode selection for Slow pads
    pub enum SlowPadOutputCodes {
        MediumDriverSharpEdge = 0b00,
        MediumDriver = 0b01,
    }

    /// Pad level selection for input function
    pub enum InputCodes {
        AutomotiveLevel = 0b00,
        TtlLevelFor5v = 0b10,
        TtlLevelFor3v = 0b11,
    }
}

macro_rules! gpio {
    ($module:ident, $PortType: ident, [
        $( $PinTypeName:ident : ( $pin_id:ident, $iocr:ident, $pdr:ident, $control_bits:ident, $read_bit:ident, $set_bit:ident, $clear_bit:ident, $pdr_pd_bit:ident, $pdr_pl_bit:ident), )+
    ]) => {

        /// This module contains HAL implementation for pins of actual port.
        pub mod $module {
            use embedded_hal::digital::v2::{InputPin, OutputPin, StatefulOutputPin, ToggleableOutputPin};
            use tc37xpd::$module::$PortType;
            use tc37xpd::$PortType;
            use super::port_control_codes;

            /// This type is defined for every port. It contains structures represented each pins of a GPIO port.
            pub struct Parts {

                $(
                    /// A pin of GPIO port.
                    pub $pin_id: $PinTypeName,
                )+
            }

            impl super::GpioExt for $PortType {
                type Parts = Parts;

                fn split(self) -> Parts {
                    Parts {
                        $(
                            $pin_id: $PinTypeName{},
                        )+
                    }
                }
            }

            $(
                /// Represents a pin.
                ///
                /// A pin implements the following traits:
                /// - [`embedded_hal::digital::v2`]`::{InputPin, OutputPin, StatefulOutputPin, ToggleableOutputPin}`
                pub struct $PinTypeName {
                }

                impl $PinTypeName {
                    /// Configure pin to pull down input pin.
                    pub fn into_pull_down_input(&self) {
                        unsafe { $PortType.$iocr().modify(|r| r.$control_bits().set(port_control_codes::INPUT_PULL_DOWN)) };
                    }

                    /// Configure pin to pull up input pin.
                    pub fn into_pull_up_input(&self){
                        unsafe { $PortType.$iocr().modify(|r| r.$control_bits().set(port_control_codes::INPUT_PULL_UP)) };
                    }

                    /// Configure pin to push pull pin.
                    pub fn into_output_push_pull(&self){
                        unsafe { $PortType.$iocr().modify(|r| r.$control_bits().set(port_control_codes::OUTPUT_PUSH_PULL)) };
                    }

                    /// Configure pin to open drain pin.
                    pub fn into_output_open_drain(&self){
                        unsafe { $PortType.$iocr().modify(|r| r.$control_bits().set(port_control_codes::OUTPUT_OPEN_DRAIN)) };
                    }

                    pub fn configure_rfast_output_pad(&self, code : super::pad_driver_codes::RFastPadOutputCodes){
                        unsafe { $PortType.$pdr().modify(|r| r.$pdr_pd_bit().set(code as u8)) };
                    }

                    pub fn configure_fast_output_pad(&self, code : super::pad_driver_codes::FastPadOutputCodes){
                        unsafe { $PortType.$pdr().modify(|r| r.$pdr_pd_bit().set(code as u8)) };
                    }

                    pub fn configure_slow_output_pad(&self, code : super::pad_driver_codes::SlowPadOutputCodes){
                        unsafe { $PortType.$pdr().modify(|r| r.$pdr_pd_bit().set(code as u8)) };
                    }

                    pub fn configure_input_pad(&self, code : super::pad_driver_codes::InputCodes){
                        unsafe { $PortType.$pdr().modify(|r| r.$pdr_pl_bit().set(code as u8)) };
                    }
                }

                impl InputPin for $PinTypeName {
                    type Error = core::convert::Infallible;

                    #[inline(always)]
                    fn is_high(&self) -> Result<bool, Self::Error> {
                        Ok( unsafe { 0 != $PortType.r#in().read().$read_bit().get().0 })
                    }

                    #[inline(always)]
                    fn is_low(&self) -> Result<bool, Self::Error> {
                        Ok(!(self.is_high().unwrap()))
                    }
                }

                impl OutputPin for $PinTypeName {
                    type Error = core::convert::Infallible;


                    #[inline(always)]
                    fn set_low(&mut self) -> Result<(), Self::Error> {
                        unsafe { $PortType.omr().init(|r| r.$clear_bit().set(1.into())) };
                        Ok(())
                    }

                    #[inline(always)]
                    fn set_high(&mut self) -> Result<(), Self::Error> {
                        unsafe { $PortType.omr().init(|r| r.$set_bit().set(1.into())) };
                        Ok(())
                    }
                }

                impl StatefulOutputPin for $PinTypeName {
                    #[inline(always)]
                    fn is_set_high(&self) -> Result<bool, Self::Error> {
                        Ok( unsafe { 0 != $PortType.r#in().read().$read_bit().get().0 })
                    }

                    #[inline(always)]
                    fn is_set_low(&self) -> Result<bool, Self::Error> {
                        Ok(!(self.is_set_high().unwrap()))
                    }
                }

                impl ToggleableOutputPin for $PinTypeName{
                    type Error = core::convert::Infallible;

                    #[inline(always)]
                    fn toggle(&mut self) -> Result<(), Self::Error>{
                        unsafe { $PortType.omr().init(|r| r.$clear_bit().set(1.into()).$set_bit().set(1.into())) };
                        Ok(())
                    }
                }
            )+
        }
    }
}

