use crate::system_timer::{DelayFunctions, SystemTimers};
use embedded_hal::blocking::delay::{DelayMs, DelayUs};
use tc37xpd::{stm0::Stm0, stm1::Stm1, stm2::Stm2, RegisterValue};

/// Macro for implementing the embedded_hal::blocking::delay functionalitie for a CPU core
/// defined in the DelayFunctions trait in tc37x_hal::system_timer
macro_rules! implement_delay_for_timer {
    ($timer:path) => {
        impl DelayFunctions for $timer {
            fn delay(&self, ticks: u64) {
                let time = self.read_ticks();
                let mut nt = time;
                while nt.wrapping_sub(time) < ticks {
                    nt = self.read_ticks();
                }
            }

            fn read_ticks(&self) -> u64 {
                let time = unsafe { self.tim0().read().get_raw() };
                let cap = unsafe { self.cap().read().get_raw() };
                (cap as u64) << 32 | (time as u64)
            }
        }
    };
}

implement_delay_for_timer!(Stm0);
implement_delay_for_timer!(Stm1);
implement_delay_for_timer!(Stm2);

/// Implementations for the DelayMs and DelayUs traits.
///
/// `DelayMs<u8>`, `DelayMs<u16>`, `DelayMs<u32>`, `DelayMs<u64>`, `DelayUs<u8>`, `DelayUs<u16>`, `DelayUs<32>`, `DelayUs<u64>` traits implemented.
/// In the implementation `tim0` and `cap` register is used to read system timer's value.  
///
/// Consider configuring timers using 64 bits long unsigned int. This type means a limit.
/// E.g. TC375 timers has default frequency 50 000 000. You cannot store larger time interval than 2^64 ticks.
/// 2 ^ 64 ticks =  `18_446_744_073_709_551_615_u64` ticks = `368_934_881_474_u64` seconds. This is the maximum delay.
///
/// Current implementation is more accurate if frequency can be divided by '1_000_000'. Computing ticks from microseconds looks like this
/// ```ignore
/// let ticks = (us.saturating_mul(self.frequency as u64)) / 1_000_000_64;
/// ```
///
/// ### Example
///
/// ```rust
/// use tc37x-hal::blocking::Delay;
/// let delay = Delay(50_000_000_u32);
/// // The following instructions will delay in current thread for 0.1 sec.
/// delay.delay_ms(100_u32);
/// delay.delay_us(100_000_u32);
/// ```
///
pub struct Delay {
    frequency: u32,
    system_timer: SystemTimers,
}

impl Delay {
    /// Creates Delay structure for the system timer of current CPU core.
    ///
    /// ### Arguments
    ///
    /// * `frequency` - Actual frequency of system timer on current CPU. Current implementation can work correctly if frequency is multiple of 1_000_000_u32.
    ///
    /// ### Examples
    ///
    /// ```rust
    /// use tc37x-hal::blocking::Delay;
    /// let delay = Delay(50_000_000_u32);
    /// ```
    ///
    pub fn new(frequency: u32) -> Self {
        Delay {
            frequency,
            system_timer: SystemTimers::new(),
        }
    }

    /// Releases the system timer (SysTick) resource.
    ///
    /// ### Example
    ///
    /// ```rust
    /// use tc37x-hal::blocking::{Delay,SystemTimers};
    /// let delay = Delay(50_000_000_u32);
    /// let timer = delay.free();
    /// ```    
    ///
    pub fn free(self) -> SystemTimers {
        self.system_timer
    }
}

const CONVERSION_MULTIPLIER_FOR_MILI: u64 = 1000_u64;
const CONVERSION_MULTIPLIER_FOR_MICRO: u64 = 1_000_000_u64;

macro_rules! impl_delay_ms {
    ($t:ty) => {
        impl DelayMs<$t> for Delay {
            #[inline]
            fn delay_ms(&mut self, ms: $t) {
                let ms = ms as u64;
                self.delay_us(ms * CONVERSION_MULTIPLIER_FOR_MILI);
            }
        }
    };
}

impl_delay_ms!(u64);
impl_delay_ms!(u32);
impl_delay_ms!(u16);
impl_delay_ms!(u8);

macro_rules! impl_delay_us {
    ($t:ty) => {
        impl DelayUs<$t> for Delay {
            #[inline]
            fn delay_us(&mut self, us: $t) {
                let us = us as u64;
                let ticks =
                    (us.saturating_mul(self.frequency as u64)) / CONVERSION_MULTIPLIER_FOR_MICRO;
                self.system_timer.get_timer().delay(ticks);
            }
        }
    };
}

impl_delay_us!(u64);
impl_delay_us!(u32);
impl_delay_us!(u16);
impl_delay_us!(u8);
