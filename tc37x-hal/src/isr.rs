use core::arch::tricore::intrinsics::__mtcr;

extern "C" {
    static __INTERRUPT_TABLE: u8;
}

/// This function will load the interrupt table using inline assembly mtcr
/// (move to core register) instruction.
///
/// Currently the interrupt table is defined in file lib.rs in inline assembly.
pub fn load_interrupt_table() {
    crate::wdtcon::call_without_cpu_endinit(|| unsafe {
        const BIV: u16 = 0xFE20;
        let interrupt_table = core::ptr::addr_of!(__INTERRUPT_TABLE) as u32;
        __mtcr::<BIV>(interrupt_table);
    });
}
