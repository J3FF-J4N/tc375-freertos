//! # Example project #2
//!
//! The first example application is part of [`tc375_bsp`] library. It demonstrates the usage of [`tc375_bsp`] and the [`tc37x_hal`] HAL implementation library.
//! The application calls higher level functions from those projects. Operations of I/O registers are in lower layers.
//!
//! The function of this example is blinking the leds and checking if button is pressed.
//! Led1 (wired on Pin05 of Port_00) and Led2 (Pin06 of Port_00) are blinked in an endless loop.
//! In that loop, the firmware checks whether the Button1 (Pin07 of Port_00) is pressed.
//! If button is pressed, the firmware will switch blinking the leds from simultaneously to alternating or backward.
//! Example runs on core CPU0. There are no more threads running on other cores.
//!
//! The example can be compiled to an elf file, which can be flashed to the Aurix TC375 Lite Kit board, with a hardware debugger or the Infineon MemTool.
//!
//! ## Entry points
//!
//! The executable has three entry points. These functions are linked together with the init script of [`tc3xx_service`] runtime library.
//!
//! 1. Pre init function
//! 2. Post init function
//! 3. Main function
//!
//!
//! ## Pre init function
//!
//! Pre init function ( `pre_init_fn` ) does the following:
//! 1. turns off system safety watchdog,
//! 2. turns off CPU watchdog.
//!
//! ## Post Init function
//!
//! Post init function ( `post_init_fn` ) does the following:
//! 1. loads the interrupt table for the CPU in a special core register.
//!
//! ## Main Function
//!
//! The `main` function follows through the following steps:
//! 1. Initializes leds and buttons by creating object of structures:
//!     - [`tc375_bsp::leds_and_buttons::Led1`]
//!     - [`tc375_bsp::leds_and_buttons::Led2`]  
//!     - [`tc375_bsp::leds_and_buttons::Button1`]
//! 3. In an endless loop:
//!     - delays for .5 secs and
//!     - toggles Led1
//!     - checks whether Button1 is pressed, and changes blinking mode of Led2
//!     - toggles Led2
//!

#![no_std]
#![no_main]

use tc37x_hal::tc3xx_service;

use tc37x_hal::isr::load_interrupt_table;
use tc37x_hal::wdtcon::{disable_cpu_watchdog, disable_safety_watchdog};
use tc3xx_service::asm_calls::read_cpu_core_id;
use tc3xx_service::{entry, post_init, pre_init};

use embedded_hal::blocking::delay::DelayMs;
use tc375_bsp::leds_and_buttons::{Button1, Led1, Led2};
use tc37x_hal::blocking::delay::Delay;

pre_init!(pre_init_fn);

fn pre_init_fn() {
    if read_cpu_core_id() == 0 {
        disable_safety_watchdog();
    }
    disable_cpu_watchdog();
}

post_init!(post_init_fn);

fn post_init_fn() {
    load_interrupt_table();
}

entry!(main);

fn main() -> ! {
    let mut led1 = Led1::new();
    let mut led2 = Led2::new();
    let button1 = Button1::new();
    let mut led2_state = false;
    let mut delay = Delay::new(tc375_bsp::SYSTEM_TIMER_FREQ_HZ);
    loop {
        delay.delay_ms(10000_u32);
        led1.toggle();
        // if button1.is_pressed() {
        //     led2_state = !led2_state;
        // }
        // set_led2(led2_state, &mut led2);
        // led2_state = !led2_state;
    }
}

fn set_led2(state: bool, led2: &mut Led2) {
    if state {
        led2.set_on();
    } else {
        led2.set_off();
    }
}
